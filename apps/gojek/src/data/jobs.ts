export function getJob(slug: string): Job | undefined {
  return JOBS.find((job) => job.slug === slug);
}

export function filterJobs(location: string, team: JobTeam | "all"): Job[] {
  return JOBS.filter((job) => {
    const locationOk = location === "All locations" || job.location === location;
    const teamOk = team === "all" || job.team === team;
    return locationOk && teamOk;
  });
}
