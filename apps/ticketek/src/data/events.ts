const bySlug = new Map(events.map((e) => [e.slug, e]));

export function getEvent(slug: string): EventItem | undefined {
  return bySlug.get(slug);
}

export function requireEvent(slug: string): EventItem {
  const event = bySlug.get(slug);
  if (!event) throw new Error(`Unknown event ${slug}`);
  return event;
}

export function findPerformance(performanceId: string): { event: EventItem; performance: Performance } | undefined {
  for (const event of events) {
    const performance = event.performances.find((p) => p.id === performanceId);
    if (performance) return { event, performance };
  }
  return undefined;
}

export function fromPrice(event: EventItem): number {
  const prices = event.priceCategories.filter((p) => p.status !== "exhausted").map((p) => p.price);
  return prices.length ? Math.min(...prices) : 0;
}

export function nextPerformance(event: EventItem, from: Date = new Date()): Performance | undefined {
  return event.performances
    .filter((p) => p.status !== "cancelled" && new Date(p.startsAt) >= from)
    .sort((a, b) => a.startsAt.localeCompare(b.startsAt))[0];
}
