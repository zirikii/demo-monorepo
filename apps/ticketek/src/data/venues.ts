const byId = new Map(venues.map((v) => [v.id, v]));

export function getVenue(id: string): Venue | undefined {
  return byId.get(id);
}

export function requireVenue(id: string): Venue {
  const venue = byId.get(id);
  if (!venue) throw new Error(`Unknown venue ${id}`);
  return venue;
}
