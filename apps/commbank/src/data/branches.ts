export type BranchFilters = {
  query: string;
  state: string;
  type: string;
};

export function filterBranches(all: Branch[], { query, state, type }: BranchFilters): Branch[] {
  const needle = query.trim().toLowerCase();
  return all.filter((branch) => {
    if (state !== "all" && branch.state !== state) return false;
    if (type !== "all" && branch.type !== type) return false;
    if (!needle) return true;
    return (
      branch.name.toLowerCase().includes(needle) ||
      branch.suburb.toLowerCase().includes(needle) ||
      branch.postcode.includes(needle) ||
      branch.address.toLowerCase().includes(needle)
    );
  });
}
